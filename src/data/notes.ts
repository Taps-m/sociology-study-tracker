/**
 * The Sleepy Classes notes, as a map of sections to pages.
 *
 * Headings and page numbers only — never a word of the notes themselves. The
 * text is copyrighted and this repository is public, so it lives in
 * `book-text/` on the device, git-ignored, and reaches the model from the
 * browser at request time. This file is the index saying which pages a topic
 * needs; `notesStore.ts` holds the pages.
 *
 * Built twice. The first attempt matched topic names to headings on shared
 * words and mapped 84 of the 85 topics, which looked like coverage and was
 * not: two fifths of the ranges ended before they began, because a section's
 * end was computed as the next heading's page minus one and two headings often
 * share a page. Worse, a single shared word was enough to match, so "Problems
 * relating to old age" was filed under "Environmental Problems".
 *
 * This one proposes with the heading and disposes with the text. A heading has
 * to share weighted, stemmed words with the topic — stemmed because "age" and
 * "ageing" are the same claim — and then the section's own body has to contain
 * the topic's distinctive words at least three times. Simmel matched a heading
 * on "forms" and "social" and was thrown out by that check, which is correct:
 * he genuinely is not in these notes.
 *
 * Result: 38 topics of 85, each verified, and 47 that honestly say there is no
 * section. Fewer than before and right, rather than more and wrong — a wrong
 * citation sends the model six irrelevant pages and the answer quietly gets
 * worse with nothing on screen to say why.
 */
export interface NoteSection {
  paper: 1 | 2;
  heading: string;
  /** First and last page of the section, 1-based, as the PDF numbers them. */
  from: number;
  to: number;
}

